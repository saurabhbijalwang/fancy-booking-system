CREATE TABLE bidder (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(80) NOT NULL,
    email VARCHAR(160) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE auction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    status VARCHAR(16) NOT NULL,
    starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at TIMESTAMP WITH TIME ZONE NOT NULL,
    starting_bid BIGINT NOT NULL,
    current_bid BIGINT NOT NULL,
    bid_sequence BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT auction_status_check CHECK (status IN ('OPEN', 'ENDED')),
    CONSTRAINT auction_bid_check CHECK (starting_bid >= 0 AND current_bid >= starting_bid)
);

CREATE TABLE bid (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auction_id BIGINT NOT NULL REFERENCES auction(id),
    bidder_id BIGINT NOT NULL REFERENCES bidder(id),
    sequence_number BIGINT NOT NULL,
    amount BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT bid_auction_sequence_unique UNIQUE (auction_id, sequence_number)
);

CREATE INDEX bid_auction_sequence_idx ON bid (auction_id, sequence_number);
CREATE INDEX auction_status_ends_at_idx ON auction (status, ends_at);
